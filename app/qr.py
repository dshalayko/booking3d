"""QR со ссылкой на бота — рисует сервер.

PIN выдаёт бот, а клавиатура стоит на планшете, прикрученном к стене: набрать
адрес бота человеку неоткуда — с чужого экрана ссылку не скопируешь, а имя
угадывают с ошибкой. Поэтому под клавиатурой живёт кнопка, которая показывает
QR: телефон наводят на стену и попадают в переписку с ботом.

Картинка не приходит из сети ни в каком виде — ни ссылкой на чужой генератор
QR, ни файлом: экраны киоска должны читаться, когда связь пропала, а это ровно
тот момент, когда к планшету и подходят. Код считается один раз при старте и
уезжает в страницу инлайновым SVG — те же полтора килобайта, что и любая
разметка, без второго запроса и без внешнего скрипта (правило про
единственный внешний скрипт см. в templates/base.html).

Имени бота нет в коде: оно в `TG_BOT_USERNAME`, рядом с токеном. Пусто —
кнопки нет, под клавиатурой остаётся прежняя строчка про /start.
"""

import segno

from app.config import settings


def bot_username() -> str:
    """Имя бота без ведущей собаки: в ссылку она не входит, в подпись — да."""
    return settings.tg_bot_username.strip().lstrip("@")


def bot_url() -> str:
    name = bot_username()
    return f"https://t.me/{name}" if name else ""


def bot_qr_svg() -> str:
    """Инлайновый SVG с QR на бота. Пусто, если имя бота не задано."""
    url = bot_url()
    if not url:
        return ""
    # `omitsize` убирает width/height: размер задаёт CSS, а на киоске и на
    # телефоне он разный. Рамка в два модуля — это тихая зона, без неё
    # сканеры цепляют край карточки за данные.
    return segno.make(url, error="m").svg_inline(
        border=2,
        dark="#12141a",
        omitsize=True,
        svgclass="qr",
        lineclass="qr-line",
    )

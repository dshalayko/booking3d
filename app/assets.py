"""Версия того, что браузер держит у себя: шаблоны, стили, скрипт.

Планшет на стене — это открытая вкладка, которая живёт неделями. Раньше правка
стилей доезжала до неё только пешком: подойти и перезагрузить страницу. Причём
понять со стороны, что доска отстала, нельзя — она рисуется и выглядит рабочей,
просто по-старому.

Поэтому у отданного браузеру есть номер. Он приезжает в `<body data-version>`
при загрузке и в заголовке `X-App-Version` при каждом опросе доски (main.py);
разошлись — страница перезагружает себя сама (static/app.js).

Номер — отпечаток содержимого, а не времени сборки: перезапуск контейнера без
правок не должен дёргать экраны в помещении, а правка одной буквы в шаблоне —
должен. Считается один раз при старте: файлы на проде не меняются под работающим
приложением, их приносит новый образ.
"""

import hashlib
from pathlib import Path

# Пути от корня проекта — так же, как их задают шаблоны (api/render.py) и отдача
# статики (main.py): приложение всегда запускается из корня.
WATCHED = (Path("app/templates"), Path("app/static"))


def digest() -> str:
    """Отпечаток всех файлов, которые уезжают в браузер."""
    total = hashlib.sha256()
    for root in WATCHED:
        for path in sorted(root.rglob("*")):
            if path.is_file():
                # Имя тоже в отпечаток: переименование файла меняет страницу не
                # меньше, чем правка внутри него.
                total.update(str(path).encode())
                total.update(path.read_bytes())
    return total.hexdigest()[:12]


VERSION = digest()

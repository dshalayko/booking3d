# --- бот: справка и команды --------------------------------------------------
#
# Сообщения бота читают на ходу, одним взглядом и чаще всего в списке чатов,
# где видно первую строку. Поэтому у всех BOT_*-сообщений одна форма:
#
#     <значок> что произошло — с именем машины в <b>
#     подробности: время, кто, сколько осталось
#     <пустая строка>
#     что делать и какой командой
#
# Значок один и в начале первой строки: второй в том же сообщении спорит с
# первым за внимание. Набор значков общий на все сообщения, иначе одно и то же
# событие выглядит по-разному в разных местах:
#
#     🔔 пора действовать сейчас (приглашение, бронь началась)
#     ⏰ напоминание о том, что будет
#     ⌛️ время вышло, возможность потеряна
#     ⏳ ожидание: очередь или «скоро конец»
#     🟢 свободно  🔴 занято  🟡 работа кончилась, но не освободили
#     📅 бронь     🏁 работа закончилась    👀 проверьте чужую машину
#     ⚠️ что-то не так   ⛔️ снято администратором   ✅ сделано
#     🔑 PIN   👋 приветствие   ✏️ переименование   🚪 выход   👌 всё спокойно
#
# Пустая строка отделяет «что случилось» от «что делать»: без неё команда
# теряется в тексте, а с переносом внутри абзаца — рвётся фраза. Переносы
# ставятся здесь руками, Telegram сам их не расставляет.

